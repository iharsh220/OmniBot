export function icon(name, cls = 'i') {
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true">${P[name] || ''}</svg>`;
}

/** Replace every <span data-icon="name"> with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    el.outerHTML = icon(el.dataset.icon);
  }
}

// ── Theme preference (System / Light / Dark) ──
export function getThemePref() {
  try { return localStorage.getItem('omnichat.theme') || 'system'; } catch { return 'system'; }
}
export function setThemePref(t) {
  try { localStorage.setItem('omnichat.theme', t); } catch { /* ignore */ }
  if (t === 'light' || t === 'dark') document.documentElement.setAttribute('data-theme', t);
  else document.documentElement.removeAttribute('data-theme');
}
/** Wire a .theme-switch container with buttons [data-theme-val]. */
export function bindThemeSwitch(el) {
  if (!el) return;
  el.innerHTML = ['system', 'light', 'dark'].map((t) =>
    `<button type="button" data-theme-val="${t}" title="${t[0].toUpperCase() + t.slice(1)} theme">${icon(t === 'system' ? 'monitor' : t === 'light' ? 'sun' : 'moon')}<span>${t[0].toUpperCase() + t.slice(1)}</span></button>`).join('');
  const sync = () => el.querySelectorAll('button').forEach((b) => b.classList.toggle('on', b.dataset.themeVal === getThemePref()));
  el.addEventListener('click', (e) => {
    const b = e.target.closest('button[data-theme-val]');
    if (!b) return;
    setThemePref(b.dataset.themeVal);
    sync();
  });
  sync();
}
